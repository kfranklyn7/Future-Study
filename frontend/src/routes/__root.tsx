import { Link, Outlet, createRootRoute, useRouterState } from '@tanstack/react-router'

import '../styles.css'

export const Route = createRootRoute({
  component: RootComponent,
  notFoundComponent: () => (
    <div className="py-16 text-center">
      <h1 className="page-title">Page not found</h1>
      <Link to="/" className="btn mt-4">
        Go to the course map
      </Link>
    </div>
  ),
})

const NAV = [
  { to: '/', label: 'Course map', exact: true },
  { to: '/discover', label: 'Discover' },
  { to: '/courses', label: 'Courses' },
  { to: '/programs', label: 'Programs' },
  { to: '/careers', label: 'Careers' },
  { to: '/graph', label: 'Prerequisites' },
] as const

function RootComponent() {
  // The home page (hero + course map) runs edge to edge; other pages sit in a centered column.
  const fullBleed = useRouterState({ select: (s) => s.location.pathname === '/' })

  return (
    <div className="flex min-h-screen flex-col">
      <header className="sticky top-0 z-30 h-14 shrink-0 border-b border-stone-200 bg-white">
        <div className="flex h-full items-center gap-4 px-4 sm:px-6 md:grid md:grid-cols-[1fr_auto_1fr]">
          <Link to="/" className="shrink-0 justify-self-start font-display text-xl font-semibold tracking-tight text-[#3b2a22] hover:no-underline"
            style={{ fontVariationSettings: "'SOFT' 100" }}
          >
            future<span className="text-[#9a3b52]">study</span>
          </Link>
          <nav aria-label="Main" className="flex min-w-0 gap-1 overflow-x-auto [scrollbar-width:none] text-sm font-medium whitespace-nowrap">
            {NAV.map((n) => (
              <Link
                key={n.to}
                to={n.to}
                className="rounded-md px-3 py-1.5 text-stone-600 transition-colors hover:bg-stone-100 hover:text-stone-900 hover:no-underline"
                activeProps={{ className: '!bg-accent-soft !text-accent', 'aria-current': 'page' }}
                activeOptions={{ exact: 'exact' in n, includeSearch: false }}
              >
                {n.label}
              </Link>
            ))}
          </nav>
          {/* Empty third column keeps the nav centered on wide screens. */}
          <div className="hidden md:block" />
        </div>
      </header>
      <main className={fullBleed ? 'flex-1' : 'mx-auto w-full max-w-6xl flex-1 px-4 pt-8 pb-16 sm:px-8'}>
        <Outlet />
      </main>
      <footer className="border-t border-stone-200 px-4 py-6 text-center text-xs text-stone-500">
        Course data from brooklyn.edu. Career paths and resources are generated by Snowflake Cortex, so verify them
        before relying on them.
      </footer>
    </div>
  )
}
